import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import {
  APPLICATION_TABLES,
  createPgliteDestination,
  discoverDrizzleTableNames,
  MigrationCommittedManifestError,
  migratePgliteSnapshot,
  type TransactionalConnection,
  writeManifest,
} from "../../../scripts/lib/pglite-postgres-migration";
import {
  seedMigrationFixture,
  setMigrationFixtureSchemaToVersion15,
} from "./pglite-postgres-migration.test-fixture";

/**
 * Timeout for the snapshot build (`beforeAll`) and each of the six migration tests (task #1190). Every test
 * restores the snapshot into its own fresh in-memory PGlite, so the cost is the same order for all of them.
 * Measured with the file alone on a shared box already at 70–100 % CPU: beforeAll ≈ 2 s, tests 4.2–7.9 s; with
 * four test files in parallel on the same box 5.1–23.6 s. In the #1145 release preflight (47 other node
 * processes, machine at 100 %) two of them ran past the old 120 s — more than 15× their alone time — so 5× the
 * idle time (≈ 40 s) and the 120 s floor were both still reachable by load; this is the 600 s ceiling the task
 * allows. A genuine hang still fails, ten minutes in instead of two.
 */
const MIGRATION_TEST_TIMEOUT_MS = 600_000;

const expectedTables = [
  "account",
  "activity",
  "agent_request",
  "api_token",
  "asset",
  "collaborator",
  "document",
  "notification",
  "ownership_transfer",
  "recent",
  "review",
  "session",
  "star",
  "user",
  "verificationToken",
  "version",
  "webhook",
  "webhook_delivery",
];

describe("PGlite to PostgreSQL migration", () => {
  let root: string;
  let snapshot: string;
  let snapshotHash: string;

  beforeAll(async () => {
    root = await fs.mkdtemp(path.join(os.tmpdir(), "markdoc-migration-"));
    snapshot = path.join(root, "fixture.tar.gz");
    const source = new PGlite("memory://");
    await source.waitReady;
    await migrate(drizzle(source), { migrationsFolder: path.resolve("drizzle") });
    await source.query(`ALTER TABLE "version" ALTER COLUMN "number" ADD GENERATED BY DEFAULT AS IDENTITY`);
    await seedMigrationFixture(source);
    await setMigrationFixtureSchemaToVersion15(source);
    const sequence = await source.query<{ name: string | null }>(
      `SELECT pg_get_serial_sequence('"version"', 'number') AS name`,
    );
    await source.query(`SELECT setval($1::regclass, $2::bigint, true)`, [sequence.rows[0].name, "41"]);
    const archive = await source.dumpDataDir("gzip");
    await fs.writeFile(snapshot, new Uint8Array(await archive.arrayBuffer()));
    await source.close();
    snapshotHash = await fileHash(snapshot);
  }, MIGRATION_TEST_TIMEOUT_MS);

  afterAll(async () => {
    await fs.rm(root, { recursive: true, force: true });
  });

  it("guards the exhaustive Drizzle table list", () => {
    expect([...APPLICATION_TABLES]).toEqual(expectedTables);
    expect(discoverDrizzleTableNames()).toEqual(expectedTables);
  });

  it("preserves Unicode, nulls, timestamps, JSON, binary values, foreign keys, and sequences", async () => {
    const destination = await createDestination(true);
    const manifestPath = path.join(root, "fidelity-manifest.json");
    try {
      await destination.query(`CREATE SCHEMA shadow`);
      await destination.query(`CREATE TABLE shadow."user" (id text PRIMARY KEY)`);
      await destination.query(`INSERT INTO shadow."user" (id) VALUES ('shadow-user')`);
      await destination.query(`SET search_path = shadow, public`);
      const manifest = await migratePgliteSnapshot({
        sourceSnapshot: snapshot,
        sourceDataDir: path.join(root, "restore-fidelity"),
        destination,
        manifestPath,
      });

      expect(manifest.totals).toEqual({ tables: expectedTables.length, rows: 18 });
      expect(manifest.records.assets).toMatchObject({ count: 2, bytes: 1_048_579 });
      expect(manifest.schema.source).toMatchObject({ count: 15, latestCreatedAt: "1787795284192" });
      expect(manifest.schema.target).toMatchObject({ count: 20, latestCreatedAt: "1788219322678" });
      expect(JSON.stringify(manifest)).not.toContain("account-access-value");
      expect(JSON.stringify(manifest)).not.toContain("https://fixture.invalid/hook");
      expect(JSON.stringify(manifest)).not.toContain("Unicode");
      expect(JSON.parse(await fs.readFile(manifestPath, "utf8"))).toEqual(manifest);
      await expect(writeManifest(snapshot, manifest)).rejects.toMatchObject({ code: "EEXIST" });
      expect(await fileHash(snapshot)).toBe(snapshotHash);

      const document = await destination.query<{
        title: string;
        content: string;
        ystate: Uint8Array;
        published_at: string;
        deleted_at: string;
      }>(
        `SELECT title, content, ystate,
                to_char(published_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US') AS published_at,
                deleted_at::text AS deleted_at
           FROM document WHERE id = 'doc-1'`,
      );
      expect(document.rows[0]).toMatchObject({
        title: "Unicode café 🚀",
        content: "# Unicode\n\nΚαλημέρα 世界",
        published_at: "2026-08-27T12:34:56.123456",
        deleted_at: "infinity",
      });
      expect([...document.rows[0].ystate]).toEqual([0, 1, 2, 255]);

      const activity = await destination.query<{ detail: Record<string, unknown> }>(
        `SELECT detail FROM activity WHERE id = 'activity-1'`,
      );
      expect(activity.rows[0].detail).toEqual({ nested: { enabled: true }, values: [1, null, "é"] });

      const assets = await destination.query<{ id: string; size: number; bytes: number }>(
        `SELECT id, size, octet_length(data) AS bytes FROM asset ORDER BY id`,
      );
      expect(assets.rows).toEqual([
        { id: "asset-big", size: 1_048_579, bytes: 1_048_579 },
        { id: "asset-empty", size: 0, bytes: 0 },
      ]);

      const nullable = await destination.query<{ email: string | null; image: string | null }>(
        `SELECT email, image FROM public."user" WHERE id = 'user-1'`,
      );
      expect(nullable.rows[0]).toEqual({ email: null, image: null });
      const shadow = await destination.query<{ id: string }>(`SELECT id FROM shadow."user"`);
      expect(shadow.rows).toEqual([{ id: "shadow-user" }]);
      const historicalTimestamp = await destination.query<{ matches: boolean }>(
        `SELECT expires_at = $1::timestamptz AS matches FROM api_token WHERE id = 'api-token-1'`,
        ["0001-02-03 04:05:06.123456+00 BC"],
      );
      expect(historicalTimestamp.rows[0].matches).toBe(true);

      const next = await destination.query<{ value: string }>(
        `SELECT nextval(pg_get_serial_sequence('"version"', 'number'))::text AS value`,
      );
      expect(next.rows[0].value).toBe("42");
      expect(await fileHash(snapshot)).toBe(snapshotHash);
      await expect(fs.stat(path.join(root, "restore-fidelity"))).rejects.toMatchObject({ code: "ENOENT" });
    } finally {
      await destination.close();
    }
  }, MIGRATION_TEST_TIMEOUT_MS);

  it("refuses a non-empty destination without changing it", async () => {
    const destination = await createDestination(true);
    const manifestPath = path.join(root, "refusal-manifest.json");
    try {
      await destination.query(`INSERT INTO "user" (id, name) VALUES ('existing-user', 'Existing')`);
      await expect(
        migratePgliteSnapshot({
          sourceSnapshot: snapshot,
          sourceDataDir: path.join(root, "restore-refusal"),
          destination,
          manifestPath,
        }),
      ).rejects.toThrow(/Destination is not empty/);
      const users = await destination.query<{ id: string }>(`SELECT id FROM "user" ORDER BY id`);
      expect(users.rows).toEqual([{ id: "existing-user" }]);
      await expect(fs.stat(manifestPath)).rejects.toMatchObject({ code: "ENOENT" });
    } finally {
      await destination.close();
    }
  }, MIGRATION_TEST_TIMEOUT_MS);

  it("rolls replacement back to the previous state on failure", async () => {
    const destination = await createDestination(true);
    const manifestPath = path.join(root, "rollback-manifest.json");
    try {
      await destination.query(`INSERT INTO "user" (id, name) VALUES ('previous-user', 'Previous')`);
      await expect(
        migratePgliteSnapshot({
          sourceSnapshot: snapshot,
          sourceDataDir: path.join(root, "restore-rollback"),
          destination,
          manifestPath,
          replace: true,
          hooks: {
            afterTable(table) {
              if (table === "document") throw new Error("injected migration failure");
            },
          },
        }),
      ).rejects.toThrow("injected migration failure");
      const users = await destination.query<{ id: string }>(`SELECT id FROM "user" ORDER BY id`);
      expect(users.rows).toEqual([{ id: "previous-user" }]);
      const documents = await destination.query<{ count: string }>(`SELECT COUNT(*)::text AS count FROM document`);
      expect(documents.rows[0].count).toBe("0");
      await expect(fs.stat(manifestPath)).rejects.toMatchObject({ code: "ENOENT" });
    } finally {
      await destination.close();
    }
  }, MIGRATION_TEST_TIMEOUT_MS);

  it("classifies manifest publication failure after the destination commit", async () => {
    const destination = await createDestination(true);
    const manifestPath = path.join(root, "post-commit-manifest.json");
    try {
      await expect(
        migratePgliteSnapshot({
          sourceSnapshot: snapshot,
          sourceDataDir: path.join(root, "restore-post-commit-manifest"),
          destination,
          manifestPath,
          hooks: {
            async afterTable(table) {
              if (table === "document") await fs.writeFile(manifestPath, "publication blocker");
            },
          },
        }),
      ).rejects.toBeInstanceOf(MigrationCommittedManifestError);
      const documents = await destination.query<{ count: string }>(`SELECT COUNT(*)::text AS count FROM document`);
      expect(documents.rows[0].count).toBe("1");
      expect(await fs.readFile(manifestPath, "utf8")).toBe("publication blocker");
      expect((await fs.readdir(root)).filter((name) => name.includes(".pending-"))).toEqual([]);
    } finally {
      await destination.close();
    }
  }, MIGRATION_TEST_TIMEOUT_MS);

  it("verify-only rejects a hash mismatch", async () => {
    const destination = await createDestination(true);
    try {
      await migratePgliteSnapshot({
        sourceSnapshot: snapshot,
        sourceDataDir: path.join(root, "restore-hash-migrate"),
        destination,
      });
      await destination.query(`UPDATE document SET content = 'changed' WHERE id = 'doc-1'`);
      await expect(
        migratePgliteSnapshot({
          sourceSnapshot: snapshot,
          sourceDataDir: path.join(root, "restore-hash-verify"),
          destination,
          verifyOnly: true,
        }),
      ).rejects.toThrow(/SHA-256 mismatch/);
    } finally {
      await destination.close();
    }
  }, MIGRATION_TEST_TIMEOUT_MS);

  it("a second migration without --replace fails and preserves all rows", async () => {
    const destination = await createDestination(true);
    try {
      await migratePgliteSnapshot({
        sourceSnapshot: snapshot,
        sourceDataDir: path.join(root, "restore-first"),
        destination,
      });
      const before = await destination.query<{ count: string }>(`SELECT COUNT(*)::text AS count FROM document`);
      await expect(
        migratePgliteSnapshot({
          sourceSnapshot: snapshot,
          sourceDataDir: path.join(root, "restore-second"),
          destination,
        }),
      ).rejects.toThrow(/Destination is not empty/);
      const after = await destination.query<{ count: string }>(`SELECT COUNT(*)::text AS count FROM document`);
      expect(after.rows[0]).toEqual(before.rows[0]);
    } finally {
      await destination.close();
    }
  }, MIGRATION_TEST_TIMEOUT_MS);
});

async function createDestination(withIdentity = false): Promise<TransactionalConnection> {
  const client = new PGlite("memory://");
  await client.waitReady;
  await migrate(drizzle(client), { migrationsFolder: path.resolve("drizzle") });
  if (withIdentity) {
    await client.query(`ALTER TABLE "version" ALTER COLUMN "number" ADD GENERATED BY DEFAULT AS IDENTITY`);
  }
  return createPgliteDestination(client);
}

async function fileHash(file: string): Promise<string> {
  const { createHash } = await import("node:crypto");
  return createHash("sha256").update(await fs.readFile(file)).digest("hex");
}
