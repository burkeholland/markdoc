import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import { createPgliteDestination, type TransactionalConnection } from "../../../scripts/lib/pglite-postgres-migration";
import {
  seedMigrationFixture,
  setMigrationFixtureSchemaToVersion15,
} from "./pglite-postgres-migration.test-fixture";

/**
 * Shared fixture of the `pglite-postgres-migration.*.test.ts` files. Task #1426 split the former
 * `pglite-postgres-migration.test.ts` (7 tests, the unit suite's longest file: ≈ 26 s alone, 31–38 s inside a
 * four-worker run, 47–105 s under load) by scenario — `.data`, `.safety`, `.failure` — because vitest parallelises
 * files, not tests, so shortening its tail meant cutting it up (12 / 11 / 9 s alone). Everything the old file built
 * once per file (`beforeAll`, `afterAll`, `createDestination`, `fileHash`, the timeout) moved here unchanged; each
 * split file builds its own snapshot through `createMigrationFixture()` in its `beforeAll`. Not a test file: no
 * `.test.` in the name, so vitest never collects it.
 */

/**
 * Timeout for the snapshot build (`beforeAll`) and each migration test (task #1190). Every test restores the
 * snapshot into its own fresh in-memory PGlite, so the cost is the same order for all of them. Measured with the
 * file alone on a shared box already at 70–100 % CPU: beforeAll ≈ 2 s, tests 4.2–7.9 s; with four test files in
 * parallel on the same box 5.1–23.6 s. In the #1145 release preflight (47 other node processes, machine at 100 %)
 * two of them ran past the old 120 s — more than 15× their alone time — so 5× the idle time (≈ 40 s) and the 120 s
 * floor were both still reachable by load; this is the 600 s ceiling the task allows. A genuine hang still fails,
 * ten minutes in instead of two.
 */
export const MIGRATION_TEST_TIMEOUT_MS = 600_000;

export interface MigrationSnapshotFixture {
  /** Temporary directory the snapshot lives in; tests put their manifest and restore paths under it. */
  root: string;
  /** The gzip PGlite data-dir archive (`fixture.tar.gz`) every test migrates from. */
  snapshot: string;
  /** SHA-256 of `snapshot` right after it was written, so tests can prove the migration never touched the source. */
  snapshotHash: string;
  /** The former `afterAll`: removes `root` and everything under it. */
  cleanup(): Promise<void>;
}

/**
 * The former `beforeAll`: a fresh in-memory PGlite at the current schema, seeded, rolled back to schema version
 * 15 and dumped to `fixture.tar.gz` in a fresh temporary directory. Removes the directory again if any step fails,
 * as the old `afterAll` did.
 */
export async function createMigrationFixture(): Promise<MigrationSnapshotFixture> {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "markdoc-migration-"));
  const cleanup = () => fs.rm(root, { recursive: true, force: true });
  try {
    const snapshot = path.join(root, "fixture.tar.gz");
    const source = new PGlite("memory://");
    await source.waitReady;
    await migrate(drizzle(source), { migrationsFolder: path.resolve("drizzle") });
    await source.query(`ALTER TABLE "version" ALTER COLUMN "number" ADD GENERATED BY DEFAULT AS IDENTITY`);
    await seedMigrationFixture(source);
    await setMigrationFixtureSchemaToVersion15(source);
    const sequence = await source.query<{ name: string | null }>(
      `SELECT pg_get_serial_sequence('"version"', 'number') AS name`,
    );
    await source.query(`SELECT setval($1::regclass, $2::bigint, true)`, [sequence.rows[0].name, "41"]);
    const archive = await source.dumpDataDir("gzip");
    await fs.writeFile(snapshot, new Uint8Array(await archive.arrayBuffer()));
    await source.close();
    const snapshotHash = await fileHash(snapshot);
    return { root, snapshot, snapshotHash, cleanup };
  } catch (error) {
    await cleanup();
    throw error;
  }
}

export async function createDestination(withIdentity = false): Promise<TransactionalConnection> {
  const client = new PGlite("memory://");
  await client.waitReady;
  await migrate(drizzle(client), { migrationsFolder: path.resolve("drizzle") });
  if (withIdentity) {
    await client.query(`ALTER TABLE "version" ALTER COLUMN "number" ADD GENERATED BY DEFAULT AS IDENTITY`);
  }
  return createPgliteDestination(client);
}

export async function fileHash(file: string): Promise<string> {
  const { createHash } = await import("node:crypto");
  return createHash("sha256").update(await fs.readFile(file)).digest("hex");
}
