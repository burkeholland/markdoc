import { spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { drizzle as drizzlePglite } from "drizzle-orm/pglite";
import { migrate as migratePglite } from "drizzle-orm/pglite/migrator";
import { drizzle as drizzlePostgres } from "drizzle-orm/node-postgres";
import { migrate as migratePostgres } from "drizzle-orm/node-postgres/migrator";
import { Client } from "pg";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import {
  APPLICATION_TABLES,
  createPostgresClientConfig,
  createPostgresDestination,
  migratePgliteSnapshot,
  type MigrationManifest,
} from "../../../scripts/lib/pglite-postgres-migration";
import {
  seedMigrationFixture,
  setMigrationFixtureSchemaToVersion15,
} from "./pglite-postgres-migration.test-fixture";

const integrationEnvironmentName = "MARKDOC_PG_INTEGRATION_URL";
const evidenceEnvironmentName = "MARKDOC_PG_INTEGRATION_EVIDENCE";
const describePostgres = process.env[integrationEnvironmentName] ? describe : describe.skip;

describePostgres("PGlite to PostgreSQL 16 CLI integration", () => {
  let root: string;
  let snapshot: string;

  beforeAll(async () => {
    root = await fs.mkdtemp(path.join(os.tmpdir(), "markdoc-pg-integration-"));
    snapshot = path.join(root, "fixture.tar.gz");

    const target = new Client(createPostgresClientConfig(integrationUrl()));
    await target.connect();
    try {
      const initialTables = await target.query<{ count: string }>(
        `SELECT COUNT(*)::text AS count
           FROM information_schema.tables
          WHERE table_schema = 'public' AND table_type = 'BASE TABLE'`,
      );
      expect(initialTables.rows[0].count).toBe("0");
      await migratePostgres(drizzlePostgres(target), { migrationsFolder: path.resolve("drizzle") });
      await target.query(`ALTER TABLE "version" ALTER COLUMN "number" ADD GENERATED BY DEFAULT AS IDENTITY`);
    } finally {
      await target.end();
    }

    const source = new PGlite("memory://");
    await source.waitReady;
    try {
      await migratePglite(drizzlePglite(source), { migrationsFolder: path.resolve("drizzle") });
      await source.query(`ALTER TABLE "version" ALTER COLUMN "number" ADD GENERATED BY DEFAULT AS IDENTITY`);
      await seedMigrationFixture(source);
      await setMigrationFixtureSchemaToVersion15(source);
      const sequence = await source.query<{ name: string | null }>(
        `SELECT pg_get_serial_sequence('"version"', 'number') AS name`,
      );
      await source.query(`SELECT setval($1::regclass, $2::bigint, true)`, [sequence.rows[0].name, "41"]);
      const archive = await source.dumpDataDir("gzip");
      await fs.writeFile(snapshot, new Uint8Array(await archive.arrayBuffer()));
    } finally {
      await source.close();
    }
  }, 180_000);

  afterAll(async () => {
    if (root) await fs.rm(root, { recursive: true, force: true });
  });

  it("migrates, verifies, refuses, detects corruption, and rolls replacement back over TLS", async () => {
    const url = integrationUrl();
    const migrateManifestPath = path.join(root, "migrate-manifest.json");
    const migration = await runCliProcess(baseArguments("restore-migrate", migrateManifestPath), url);
    assertSecretFree(migration, url);
    expect(migration.exitCode).toBe(0);
    const manifest = JSON.parse(await fs.readFile(migrateManifestPath, "utf8")) as MigrationManifest;
    expect(manifest.totals).toEqual({ tables: 17, rows: 18 });
    expect(Object.keys(manifest.tables).sort()).toEqual([...APPLICATION_TABLES]);
    expect(manifest.records).toMatchObject({
      documents: { count: 1 },
      assets: { count: 2, bytes: 1_048_579 },
    });
    expect(Object.keys(manifest.sequences)).toEqual(["version.number"]);

    const proof = await createPostgresDestination(url);
    let postgresVersion = "";
    let serverVersionNumber = "";
    try {
      const transport = await proof.query<{
        postgres_version: string;
        server_version_number: string;
        ssl: boolean;
      }>(
        `SELECT version() AS postgres_version,
                current_setting('server_version_num') AS server_version_number,
                (SELECT ssl FROM pg_stat_ssl WHERE pid = pg_backend_pid()) AS ssl`,
      );
      postgresVersion = transport.rows[0].postgres_version;
      serverVersionNumber = transport.rows[0].server_version_number;
      expect(serverVersionNumber.startsWith("16")).toBe(true);
      expect(transport.rows[0].ssl).toBe(true);

      const counts = await proof.query<{ table_name: string; row_count: string }>(
        `SELECT table_name,
                (xpath('/row/count/text()', query_to_xml(
                  format('SELECT count(*) AS count FROM public.%I', table_name),
                  false, true, ''
                )))[1]::text::bigint::text AS row_count
           FROM information_schema.tables
          WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
          ORDER BY table_name`,
      );
      expect(counts.rows.map((row) => row.table_name)).toEqual([...APPLICATION_TABLES]);
      expect(counts.rows.reduce((total, row) => total + Number(row.row_count), 0)).toBe(18);

      const document = await proof.query<{ title: string; content: string; ystate_hex: string }>(
        `SELECT title, content, encode(ystate, 'hex') AS ystate_hex FROM document WHERE id = 'doc-1'`,
      );
      expect(document.rows[0]).toEqual({
        title: "Unicode café 🚀",
        content: "# Unicode\n\nΚαλημέρα 世界",
        ystate_hex: "000102ff",
      });
      const assets = await proof.query<{ id: string; bytes: number }>(
        `SELECT id, octet_length(data) AS bytes FROM asset ORDER BY id`,
      );
      expect(assets.rows).toEqual([
        { id: "asset-big", bytes: 1_048_579 },
        { id: "asset-empty", bytes: 0 },
      ]);
      const sequence = await proof.query<{ last_value: string; is_called: boolean }>(
        `SELECT last_value::text, is_called FROM public.version_number_seq`,
      );
      expect(sequence.rows[0]).toEqual({ last_value: "42", is_called: false });
    } finally {
      await proof.close();
    }

    const refusalManifestPath = path.join(root, "refusal-manifest.json");
    const refusal = await runCliProcess(baseArguments("restore-refusal", refusalManifestPath), url);
    assertSecretFree(refusal, url);
    expect(refusal.exitCode).toBe(1);
    expect(refusal.stderr).toMatch(/Destination is not empty/);
    await expect(fs.stat(refusalManifestPath)).rejects.toMatchObject({ code: "ENOENT" });

    const verifyManifestPath = path.join(root, "verify-manifest.json");
    const verification = await runCliProcess(
      [...baseArguments("restore-verify", verifyManifestPath), "--verify-only"],
      url,
    );
    assertSecretFree(verification, url);
    expect(verification.exitCode).toBe(0);
    expect(JSON.parse(await fs.readFile(verifyManifestPath, "utf8"))).toEqual(manifest);

    const corrupt = await createPostgresDestination(url);
    try {
      await corrupt.query(`UPDATE document SET content = 'corrupt' WHERE id = 'doc-1'`);
    } finally {
      await corrupt.close();
    }
    const mismatch = await runCliProcess(
      [...baseArguments("restore-mismatch", path.join(root, "mismatch-manifest.json")), "--verify-only"],
      url,
    );
    assertSecretFree(mismatch, url);
    expect(mismatch.exitCode).toBe(1);
    expect(mismatch.stderr).toMatch(/SHA-256 mismatch/);

    const previous = await createPostgresDestination(url);
    try {
      await previous.query(`UPDATE document SET content = $1 WHERE id = 'doc-1'`, ["previous target state"]);
    } finally {
      await previous.close();
    }
    const replacement = await createPostgresDestination(url);
    try {
      await expect(
        migratePgliteSnapshot({
          sourceSnapshot: snapshot,
          sourceDataDir: path.join(root, "restore-replace-rollback"),
          destination: replacement,
          replace: true,
          hooks: {
            afterTable(table) {
              if (table === "document") throw new Error("injected PostgreSQL replacement failure");
            },
          },
        }),
      ).rejects.toThrow("injected PostgreSQL replacement failure");
    } finally {
      await replacement.close();
    }
    const rollbackProof = await createPostgresDestination(url);
    try {
      const result = await rollbackProof.query<{ content: string; rows: string }>(
        `SELECT content, (SELECT SUM(count)::text FROM (
           SELECT (xpath('/row/count/text()', query_to_xml(
             format('SELECT count(*) AS count FROM public.%I', table_name),
             false, true, ''
           )))[1]::text::bigint AS count
             FROM information_schema.tables
            WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
         ) counts) AS rows
           FROM document WHERE id = 'doc-1'`,
      );
      expect(result.rows[0]).toEqual({ content: "previous target state", rows: "18" });
    } finally {
      await rollbackProof.close();
    }

    const evidencePath = process.env[evidenceEnvironmentName];
    if (evidencePath) {
      await fs.writeFile(
        evidencePath,
        `${JSON.stringify(
          {
            postgresVersion,
            serverVersionNumber,
            ssl: true,
            tlsContract: "sslmode=require encryption on a private-IP endpoint; certificate identity is not validated",
            manifest: {
              tables: manifest.totals.tables,
              rows: manifest.totals.rows,
              documents: manifest.records.documents.count,
              assets: manifest.records.assets.count,
              assetBytes: manifest.records.assets.bytes,
              sourceSchemaMigrations: manifest.schema.source.count,
              targetSchemaMigrations: manifest.schema.target.count,
              sequences: Object.keys(manifest.sequences).length,
            },
            cli: { migrationExit: migration.exitCode, verifyOnlyExit: verification.exitCode },
            refusal: { exit: refusal.exitCode, rowsUnchanged: true },
            hashMismatch: { exit: mismatch.exitCode, detected: true },
            replaceRollback: { priorRowsRestored: 18, priorContentRestored: true },
          },
          null,
          2,
        )}\n`,
        { encoding: "utf8", flag: "wx" },
      );
    }
  }, 300_000);

  function baseArguments(restoreName: string, manifestPath: string): string[] {
    return [
      "--source-snapshot",
      snapshot,
      "--source-data-dir",
      path.join(root, restoreName),
      "--destination-url-env",
      integrationEnvironmentName,
      "--manifest",
      manifestPath,
    ];
  }
});

function integrationUrl(): string {
  const value = process.env[integrationEnvironmentName];
  if (!value) throw new Error(`${integrationEnvironmentName} is required for the PostgreSQL integration`);
  return value;
}

interface CliProcessResult {
  exitCode: number;
  stdout: string;
  stderr: string;
}

async function runCliProcess(argumentsValue: string[], databaseUrl: string): Promise<CliProcessResult> {
  return new Promise((resolve, reject) => {
    const child = spawn(
      process.execPath,
      [
        path.resolve("node_modules", "tsx", "dist", "cli.mjs"),
        path.resolve("scripts", "migrate-pglite-to-postgres.mts"),
        ...argumentsValue,
      ],
      {
        cwd: path.resolve("."),
        env: { ...process.env, [integrationEnvironmentName]: databaseUrl },
        stdio: ["ignore", "pipe", "pipe"],
      },
    );
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");
    child.stdout.on("data", (chunk: string) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk: string) => {
      stderr += chunk;
    });
    child.once("error", reject);
    child.once("close", (code) => {
      resolve({ exitCode: code ?? -1, stdout, stderr });
    });
  });
}

function assertSecretFree(result: CliProcessResult, databaseUrl: string): void {
  const output = `${result.stdout}\n${result.stderr}`;
  const password = new URL(databaseUrl).password;
  expect(output.includes(databaseUrl)).toBe(false);
  expect(password.length > 0).toBe(true);
  expect(output.includes(password)).toBe(false);
}
